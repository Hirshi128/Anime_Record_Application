import { expect, test, type Page } from "@playwright/test";

async function dragToGrade(page: Page, title: string, grade: string) {
  const source = page.getByRole("button", { name: `${title}を移動`, exact: true });
  const target = page.getByRole("region", { name: `${grade}ティア`, exact: true }).locator(".tier-content");
  await source.scrollIntoViewIfNeeded();
  const start = (await source.boundingBox())!;
  await page.mouse.move(start.x + 20, start.y + 20);
  await page.mouse.down();
  await page.mouse.move(start.x + 30, start.y + 30, { steps: 5 });
  await target.evaluate(element => element.scrollIntoView({ block: "center", inline: "center" }));
  const end = (await target.boundingBox())!;
  await page.mouse.move(end.x + end.width - 8, end.y + end.height / 2, { steps: 12 });
  await page.waitForTimeout(50);
  await page.mouse.up();
  await page.waitForTimeout(100);
  await expect(page.getByRole("region", { name: `${grade}ティア`, exact: true }).getByRole("heading", { name: title, exact: true })).toBeVisible();
}

test("personal record CRUD, seven grades, persistence and backup without login", async ({ page }, info) => {
  const posts: string[] = [];
  page.on("request", r => { if (r.method() === "POST") posts.push(r.url()); });
  await page.route("**/api/anime-title-suggestions?*", r => r.fulfill({ json: { suggestions: [] } }));
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Anime Record" })).toBeVisible();
  await page.getByRole("button", { name: "アニメを記録", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("combobox", { name: "タイトル" }).fill("テスト作品");
  await dialog.getByLabel("見た年月").fill("2025-06");
  await dialog.getByRole("combobox", { name: "視聴状況", exact: true }).selectOption("COMPLETED");
  await dialog.locator("summary").click();
  await dialog.getByLabel("SF", { exact: true }).check();
  await dialog.locator("summary").click();
  await dialog.getByLabel("感想").fill("自分だけの感想");
  await dialog.getByRole("button", { name: "ティア表で評価", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  for (const grade of ["SS", "S", "A", "B", "C", "D", "E"]) await expect(page.getByRole("region", { name: `${grade}ティア`, exact: true })).toBeAttached();
  await dragToGrade(page, "テスト作品", "E");
  await expect(page.getByRole("region", { name: "評価待ち", exact: true })).not.toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "テスト作品" })).toBeVisible();
  await page.getByRole("button", { name: "一覧", exact: true }).click();
  await expect(page.getByText("自分だけの感想")).toBeVisible();
  await page.getByRole("button", { name: "テスト作品を編集" }).click();
  await dialog.getByLabel("見た年月").fill("2025-07");
  await dialog.getByRole("button", { name: "ティア表で評価", exact: true }).click();
  await dragToGrade(page, "テスト作品", "SS");
  await page.getByRole("button", { name: "一覧", exact: true }).click();
  await page.getByLabel("評価で絞り込み").selectOption("E");
  await expect(page.getByText("条件に合う記録がありません。")).toBeVisible();
  await page.getByLabel("評価で絞り込み").selectOption("SS");
  await expect(page.getByRole("heading", { name: "テスト作品" })).toBeVisible();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "書き出し" }).click();
  const backup = await download;
  const path = await backup.path();
  expect(path).toBeTruthy();
  await page.screenshot({ path: info.outputPath("personal-library.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  page.once("dialog", d => d.accept());
  await page.getByRole("button", { name: "テスト作品を削除" }).click();
  await expect(page.getByText("まだ記録がありません。")).toBeVisible();
  page.once("dialog", d => d.accept());
  await page.getByLabel("バックアップファイル").setInputFiles(path!);
  await expect(page.getByRole("heading", { name: "テスト作品" })).toBeVisible();
  expect(posts).toEqual([]);
  await page.goto("/users/account");
  await expect(page).toHaveURL(/\/library$/);
  await expect(page.getByRole("heading", { name: "テスト作品" })).toBeVisible();
});

test("keeps corrupt browser data untouched and prevents accidental overwrite", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("anime-record.personal.v1", "broken data"));
  await page.goto("/");
  await expect(page.getByRole("main").getByRole("alert")).toContainText("上書きを防ぐ");
  await expect(page.getByRole("button", { name: "アニメを記録", exact: true })).toBeDisabled();
  expect(await page.evaluate(() => localStorage.getItem("anime-record.personal.v1"))).toBe("broken data");
});

test("inserts a new work into the middle of a tier and reviews a selected year", async ({ page }, info) => {
  const records = ["あ", "い", "う", "え", "お", "前年"].map((title, i) => ({ id: `tier-${i}`, title,
    rating: i < 2 ? "SS" : "S", status: "COMPLETED", watchedMonth: i === 5 ? "2024-06" : "2025-06", review: "", tags: [], updatedAt: "2026-01-01T00:00:00.000Z" }));
  await page.addInitScript(value => { if (!localStorage.getItem("anime-record.personal.v1")) localStorage.setItem("anime-record.personal.v1", JSON.stringify({ version: 1, records: value })); }, records);
  await page.route("**/api/anime-title-suggestions?*", r => r.fulfill({ json: { suggestions: [] } }));
  await page.goto("/");
  const firstCard = page.locator(".tier-item").first();
  await expect(firstCard).toHaveText("2025/06あ");
  const bounds = (await firstCard.boundingBox())!;
  expect(bounds.width).toBeLessThanOrEqual(140);
  expect(bounds.height).toBeLessThanOrEqual(60);
  const dateBounds = (await firstCard.locator("time").boundingBox())!;
  const titleBounds = (await firstCard.locator(".line-clamp-2").boundingBox())!;
  expect(dateBounds.x - bounds.x).toBeLessThanOrEqual(12);
  expect(dateBounds.y - bounds.y).toBeLessThanOrEqual(6);
  expect(dateBounds.y + dateBounds.height).toBeLessThanOrEqual(titleBounds.y);
  await page.getByRole("button", { name: "アニメを記録", exact: true }).click();
  await page.getByRole("dialog").getByRole("combobox", { name: "タイトル" }).fill("か");
  await page.getByRole("dialog").getByLabel("見た年月").fill("2025-06");
  await page.getByRole("button", { name: "ティア表で評価", exact: true }).click();
  const source = page.getByRole("button", { name: "かを移動", exact: true });
  const target = page.getByRole("button", { name: "おを移動", exact: true });
  await source.scrollIntoViewIfNeeded();
  const start = (await source.boundingBox())!;
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2);
  await page.mouse.down();
  await page.mouse.move(start.x + start.width / 2 + 10, start.y + start.height / 2 + 10, { steps: 5 });
  await target.evaluate(element => element.scrollIntoView({ block: "center", inline: "center" }));
  const end = (await target.boundingBox())!;
  await page.mouse.move(end.x + 2, end.y + 5, { steps: 12 });
  await page.waitForTimeout(50);
  await page.mouse.up();
  await page.waitForTimeout(100);
  await expect(page.getByRole("region", { name: "評価待ち", exact: true })).not.toBeVisible();
  await page.getByRole("combobox", { name: "年", exact: true }).selectOption("2025");
  const tier = page.getByRole("region", { name: "Sティア", exact: true });
  await expect(tier.getByRole("heading", { level: 3 })).toHaveText(["う", "え", "か", "お"]);
  await page.reload();
  await page.getByRole("combobox", { name: "年", exact: true }).selectOption("2025");
  await expect(tier.getByRole("heading", { level: 3 })).toHaveText(["う", "え", "か", "お"]);
  await page.getByRole("button", { name: "一覧", exact: true }).click();
  await page.getByRole("button", { name: "えを編集", exact: true }).click();
  await page.getByRole("dialog").getByLabel("感想").fill("順序を変えずにコメントを更新");
  await page.getByRole("button", { name: "ティア表で評価", exact: true }).click();
  await page.getByRole("combobox", { name: "年", exact: true }).selectOption("2025");
  await expect(tier.getByRole("heading", { level: 3 })).toHaveText(["う", "え", "か", "お"]);
  await page.screenshot({ path: info.outputPath("tier-board.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("combobox", { name: "年", exact: true }).selectOption("2024");
  await expect(tier.getByRole("heading", { level: 3 })).toHaveText(["前年"]);
});
